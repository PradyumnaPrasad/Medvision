"""Deterministic, non-LLM report builder — the fallback when Ollama is unreachable or
keeps failing verification (PLAN.md: "the app must work with the LLM off").

Every sentence here is built directly from EvidenceBlock, so by construction it is
already fully grounded; medvision/pipeline.py does not run it through the verifier
and reports it with a grounding score of 1.0.
"""

from __future__ import annotations

from medvision.reasoning.schema import DifferentialItem, EvidenceBlock, LLMReport, ReportItem

__all__ = ["build_template_report", "flatten_report"]

DEFAULT_LIMITATIONS = [
    "Single frontal-view chest X-ray; no lateral view or prior studies were available "
    "for comparison.",
    "Findings were generated by an automated model and have not been reviewed by a clinician.",
    "Probabilities reflect statistical pattern matching, not clinical certainty.",
]
DEFAULT_RECOMMENDATION = (
    "Clinical correlation and review by a qualified radiologist is recommended before "
    "any diagnostic or treatment decision is made."
)


def _fact_texts(evidence: EvidenceBlock, fact_ids: list[str]) -> list[str]:
    by_id = {k.id: k.text for k in evidence.kg_facts}
    return [by_id[i] for i in fact_ids if i in by_id]


def build_template_report(evidence: EvidenceBlock) -> LLMReport:
    findings_items = []
    for f in evidence.findings:
        qualifier = "is present" if f.status == "present" else "is possibly present"
        region_clause = f", most prominent in the {f.region}" if f.region else ""
        text = f"{f.name} {qualifier} (p={f.prob:.2f}){region_clause}."
        findings_items.append(ReportItem(text=text, evidence_ids=[f.id]))

    impression_items = []
    if evidence.differentials:
        top = evidence.differentials[0]
        ids = [top.id, *top.supporting_fact_ids]
        impression_items.append(
            ReportItem(
                text=f"Findings are most consistent with {top.name} (score={top.score:.2f}).",
                evidence_ids=ids,
            )
        )
        if len(evidence.differentials) > 1:
            others = evidence.differentials[1:]
            names = ", ".join(d.name for d in others)
            impression_items.append(
                ReportItem(
                    text=f"Differential diagnoses to also consider: {names}.",
                    evidence_ids=[d.id for d in others],
                )
            )
    elif evidence.findings:
        # nothing reached the diagnosis-activation threshold, but there is at least one
        # finding to point to as the (insufficient) evidence for that
        impression_items.append(
            ReportItem(
                text="No differential diagnosis reached the activation threshold for this image.",
                evidence_ids=[f.id for f in evidence.findings],
            )
        )
    # else: no findings and no differentials at all (e.g. a normal study) — impression_items
    # stays empty; flatten_report() renders "No impression could be generated." for this case

    differential_items = [
        DifferentialItem(
            diagnosis=d.name,
            rationale="Supported by: " + "; ".join(_fact_texts(evidence, d.supporting_fact_ids)),
            evidence_ids=[d.id, *d.supporting_fact_ids],
        )
        for d in evidence.differentials
    ]

    return LLMReport(
        findings=findings_items,
        impression=impression_items,
        differentials=differential_items,
        limitations=DEFAULT_LIMITATIONS,
        recommendation=DEFAULT_RECOMMENDATION,
    )


def flatten_report(report: LLMReport, disclaimer: str) -> str:
    """Render an LLMReport (LLM- or template-sourced) as plain text, for PDF export and
    any client that just wants a string instead of the structured, citation-tagged form."""
    lines: list[str] = ["FINDINGS:"]
    if not report.findings:
        lines.append("  No findings met the reporting threshold.")
    else:
        lines += [f"  - {item.text}" for item in report.findings]

    lines += ["", "IMPRESSION:"]
    if not report.impression:
        lines.append("  No impression could be generated.")
    else:
        lines += [f"  {item.text}" for item in report.impression]

    if report.differentials:
        lines += ["", "DIFFERENTIAL DIAGNOSES:"]
        lines += [f"  - {item.diagnosis}: {item.rationale}" for item in report.differentials]

    if report.limitations:
        lines += ["", "LIMITATIONS:"]
        lines += [f"  - {lim}" for lim in report.limitations]

    lines += ["", f"RECOMMENDATION: {report.recommendation}", "", f"NOTE: {disclaimer}"]
    return "\n".join(lines)
